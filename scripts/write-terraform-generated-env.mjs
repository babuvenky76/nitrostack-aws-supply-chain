#!/usr/bin/env node
/**
 * @file write-terraform-generated-env.mjs
 * @summary Writes `supply-chain/.generated/.env` from `terraform output -json` after apply.
 * @context Public Vite/OIDC vars + `SUPPLY_CHAIN_APP_SECRET_NAME` only; no secret payloads.
 * @debugging Re-run if API URLs or Cognito ids change after `terraform apply`.
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const tfDir = join(root, 'infrastructure/terraform');

function tfOutputs() {
  const raw = execFileSync('terraform', ['-chdir', tfDir, 'output', '-json'], {
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'inherit']
  });
  return JSON.parse(raw);
}

function outVal(outputs, key) {
  const o = outputs[key];
  if (o == null || o.value === undefined) {
    throw new Error(`Missing Terraform output "${key}". Run terraform apply first.`);
  }
  return o.value;
}

const outputs = tfOutputs();
const authority = outVal(outputs, 'cognito_issuer');
const webId = outVal(outputs, 'web_client_id');
const api = outVal(outputs, 'http_api_base_url');
const secretName = outVal(outputs, 'supply_chain_app_secret_name');
const redirect = outVal(outputs, 'cognito_web_callback_primary');

const header =
  '# Generated by scripts/write-terraform-generated-env.mjs from Terraform outputs.\n' +
  '# Do not commit this file (.generated/ is gitignored).\n' +
  '# Public OIDC/API URLs + Secrets Manager secret *name* only. Sensitive values are in AWS Secrets Manager.\n\n';

const body =
  `SUPPLY_CHAIN_APP_SECRET_NAME=${secretName}\n` +
  `VITE_COGNITO_AUTHORITY=${authority}\n` +
  `VITE_COGNITO_WEB_CLIENT_ID=${webId}\n` +
  `VITE_OIDC_REDIRECT_URI=${redirect}\n` +
  `VITE_AWS_HTTP_API_BASE_URL=${api}\n` +
  `NEXT_PUBLIC_AWS_HTTP_API_BASE_URL=${api}\n`;

const dir = join(root, '.generated');
mkdirSync(dir, { recursive: true });
const dest = join(dir, '.env');
writeFileSync(dest, header + body, 'utf8');
console.error(`Wrote ${dest}`);
